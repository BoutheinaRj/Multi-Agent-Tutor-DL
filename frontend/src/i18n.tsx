const LIBELLES: Record<LangueUI, Libelles> = { fr, en, ar };

type Traduire = (cle: CleTexte, valeurs?: Record<string, string | number>) => string;
interface ContexteLangue {
  langue: LangueUI;
  setLangue: (l: LangueUI) => void;
  t: Traduire;
  rtl: boolean;
}

const Contexte = createContext<ContexteLangue | null>(null);

export function FournisseurLangue({ children }: { children: ReactNode }) {
  const [langue, setLangue] = useState<LangueUI>(() => {
    const l = localStorage.getItem("mat-langue");
    return l === "en" || l === "ar" ? l : "fr";
  });
  useEffect(() => {
    document.documentElement.lang = langue;
    document.documentElement.dir = langue === "ar" ? "rtl" : "ltr";
    localStorage.setItem("mat-langue", langue);
  }, [langue]);
  const valeur = useMemo<ContexteLangue>(() => {
    const t: Traduire = (cle, valeurs) => {
      let s = LIBELLES[langue][cle] ?? fr[cle];
      if (valeurs) for (const [k, v] of Object.entries(valeurs)) s = s.replaceAll(`{${k}}`, String(v));
      return s;
    };
    return { langue, setLangue, t, rtl: langue === "ar" };
  }, [langue]);
  return <Contexte.Provider value={valeur}>{children}</Contexte.Provider>;
}

export function useLangue(): ContexteLangue {
  const c = useContext(Contexte);
  if (!c) throw new Error("useLangue hors de FournisseurLangue");
  return c;
}

/** Date ISO (AAAA-MM-JJ) lisible dans la langue de l'interface. */
export function formaterDate(iso: string, langue: LangueUI) {
  const [a, m, j] = iso.split("-").map(Number);
  const locale = langue === "ar" ? "ar-TN" : langue === "en" ? "en-GB" : "fr-FR";
  return new Date(a, m - 1, j).toLocaleDateString(locale, { day: "numeric", month: "long" });
}
